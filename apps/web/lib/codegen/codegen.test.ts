import { beforeEach, describe, expect, it, vi } from "vitest";
import { partsById } from "@echidna/library";

import { CODE_LANGUAGES, firmwareTarget, generateCode } from ".";
import { useProjectStore } from "@/stores/project";
import { pinFromLabel } from "./model";

// The store persists to localStorage, which it looks up as it is created; Node has none to offer.
vi.hoisted(() => {
  const items = new Map<string, string>();
  Object.defineProperty(globalThis, "localStorage", {
    configurable: true,
    value: {
      getItem: (key: string) => items.get(key) ?? null,
      setItem: (key: string, value: string) => void items.set(key, value),
      removeItem: (key: string) => void items.delete(key),
    },
  });
});

const store = () => useProjectStore.getState();

/**
 * A dev board with parts plugged into its I²C and GPIO headers. The slot checks refuse parts at the wrong logic
 * level, such as a 3.3 V BME280 on the 5 V UNO R4, so each board gets parts that fit it.
 */
const build = (board: string, plug: { i2c?: string; gpio?: string }) => {
  store().loadPreset(board);
  const ids: Record<string, string> = {};
  for (const [slot, specId] of Object.entries(plug)) {
    const id = store().addComponent(specId, { x: 20, y: 6 + Object.keys(ids).length * 6 });
    if (!id) throw new Error(`${specId} not added`);
    expect(store().plugIn(id, "B1", slot)?.fits, `${specId} on ${board}`).toBe(true);
    ids[slot] = id;
  }
  return ids;
};

/** What fits each board: 3.3 V sensors on the ESP32 and Pi, the 5 V HC-SR04 on the UNO R4. */
const fitting: Record<string, { i2c?: string; gpio?: string }> = {
  "esp32-devkitc": { i2c: "bme280", gpio: "ds18b20" },
  "raspberry-pi-5": { i2c: "bme280", gpio: "ds18b20" },
  "arduino-uno-r4": { gpio: "hc-sr04" },
};

describe("pinFromLabel", () => {
  it("reads ESP32 and Pi GPIO numbers, and Arduino digital and analogue pins", () => {
    expect(pinFromLabel("GPIO21 SDA")).toMatchObject({ gpio: 21 });
    expect(pinFromLabel("D2")).toMatchObject({ gpio: 2, arduino: "2" });
    expect(pinFromLabel("A4 SDA")).toMatchObject({ gpio: 18, arduino: "A4" });
    expect(pinFromLabel("3V3")).toBeUndefined();
  });
});

describe("firmware target", () => {
  beforeEach(() => store().clear());

  it("is null without a dev board", () => {
    store().loadExample();
    expect(firmwareTarget(store(), partsById)).toBeNull();
    expect(generateCode(store(), partsById, "c")).toBeNull();
  });

  it("finds sensors in the slots and their pins", () => {
    const { i2c: bme, gpio: other } = build("esp32-devkitc", fitting["esp32-devkitc"] ?? {});
    const target = firmwareTarget(store(), partsById);
    expect(target).toMatchObject({
      family: "esp32",
      boardId: "B1",
      i2c: { sda: { gpio: 21 }, scl: { gpio: 22 } },
    });
    expect(target?.peripherals).toEqual(
      expect.arrayContaining([
        expect.objectContaining({ type: "bme280", id: bme, address: 0x76 }),
        expect.objectContaining({
          type: "ds18b20",
          id: other,
          data: expect.objectContaining({ gpio: 4 }),
        }),
      ]),
    );
  });

  it("drives a GPIO pin with an LED wired straight to it", () => {
    store().loadPreset("raspberry-pi-4");
    const led = store().addComponent("led-5mm", { x: 20, y: 6 });
    if (!led) throw new Error("no LED");
    const anode = partsById.get("led-5mm")?.pins[0]?.id ?? "";
    store().connect({ componentId: "B1", pinId: "gpio23" }, { componentId: led, pinId: anode });
    const target = firmwareTarget(store(), partsById);
    expect(target?.peripherals).toEqual([
      expect.objectContaining({ type: "output", pin: expect.objectContaining({ gpio: 23 }) }),
    ]);
  });
});

describe.each(Object.keys(fitting))("code for %s", (board) => {
  beforeEach(() => store().clear());

  it.each(CODE_LANGUAGES)("writes %s listing every plugged-in part", (language) => {
    const ids = build(board, fitting[board] ?? {});
    const code = generateCode(store(), partsById, language);
    expect(code?.code).toContain("Generated by Echidna for B1");
    // Every program, or the note standing in for one, lists the wiring.
    for (const [slot, id] of Object.entries(ids)) {
      const name = partsById.get(fitting[board]?.[slot as "i2c" | "gpio"] ?? "")?.name ?? "";
      expect(code?.code).toContain(`${id} ${name}`);
    }
    expect(code?.code.endsWith("\n")).toBe(true);
  });
});

describe("code details", () => {
  beforeEach(() => store().clear());

  it("sets up the ESP32's I2C pins and the DS18B20 in ESP-IDF C", () => {
    build("esp32-devkitc", fitting["esp32-devkitc"] ?? {});
    const code = generateCode(store(), partsById, "c")?.code ?? "";
    expect(code).toContain("#define PIN_SDA GPIO_NUM_21");
    expect(code).toContain("#define S2_PIN GPIO_NUM_4");
    expect(code).toContain("bmp280_init_desc(");
    expect(code).toContain("void app_main(void)");
  });

  it("writes an Arduino sketch timing the HC-SR04 on the UNO R4", () => {
    build("arduino-uno-r4", fitting["arduino-uno-r4"] ?? {});
    const sketch = generateCode(store(), partsById, "cpp");
    expect(sketch?.fileName).toBe("echidna.ino");
    expect(sketch?.code).toContain("const int S1_TRIG = 2; // D2");
    expect(sketch?.code).toContain("pulseIn(echo, HIGH, 30000)");
    expect(sketch?.code).toContain("--fqbn arduino:renesas_uno:minima");
  });

  it("reads the Pi's sensors through the kernel's drivers", () => {
    build("raspberry-pi-4", { i2c: "bme280", gpio: "ds18b20" });
    const code = generateCode(store(), partsById, "rust")?.code ?? "";
    expect(code).toContain("dtoverlay=i2c-sensor,bme280,addr=0x76");
    expect(code).toContain("dtoverlay=w1-gpio,gpiopin=23");
    expect(code).toContain('find("/sys/bus/w1/devices", "28-", "temperature")');
  });

  it("reads a microcontroller's serial output in Java", () => {
    build("esp32-devkitc", fitting["esp32-devkitc"] ?? {});
    const code = generateCode(store(), partsById, "java")?.code ?? "";
    expect(code).toContain("import com.fazecast.jSerialComm.SerialPort;");
    expect(code).toMatch(/Map\.entry\("S2 temperature_c", "DS18B20[^"]*, °C"\)/);
  });
});
