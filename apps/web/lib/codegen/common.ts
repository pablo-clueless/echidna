import type { FirmwareTarget, Peripheral } from "./model";

/** Languages code can be written in. */
export const CODE_LANGUAGES = ["c", "cpp", "go", "rust", "java"] as const;
export type CodeLanguage = (typeof CODE_LANGUAGES)[number];

/** Generated source: the file name to save it as and its text. */
export type GeneratedCode = { fileName: string; code: string };

/** Where every program sends its readings: one line per value, `<designator> <quantity>=<value>`. */
export const READING_FORMAT = "<designator> <quantity>=<value>";

/** Baud rate of the boards' serial output, which the host-side reader opens the port at. */
export const BAUD = 115200;

/** Speed of sound in air at 20 °C, in metres per second, for the HC-SR04's echo time. */
export const SPEED_OF_SOUND = 343;

/** The I²C address as code writes it, such as `0x76`. */
export const hex = (n: number) => `0x${n.toString(16).padStart(2, "0")}`;

const describe = (p: Peripheral, target: FirmwareTarget): string => {
  switch (p.type) {
    case "bme280":
      return `${p.id} ${p.name}: I2C on ${target.i2c?.sda.label ?? "SDA"} and ${target.i2c?.scl.label ?? "SCL"}, address ${hex(p.address)}`;
    case "ds18b20":
      return `${p.id} ${p.name}: 1-Wire data on ${p.data.label}, with a 4.7 kΩ pull-up to its supply`;
    case "hcsr04":
      return `${p.id} ${p.name}: trigger ${p.trig.label}, echo ${p.echo.label}`;
    case "i2c":
      return `${p.id} ${p.name}: on the I2C bus, with no driver here; add one for its address`;
    case "output":
      return `${p.pin.label}: output, driving ${p.name}`;
    case "input":
      return `${p.pin.label}: input, reading ${p.name}`;
  }
};

/**
 * The comment block every file starts with: what it is for, how to build it, the wiring it expects and what it
 * prints. Lines come without comment markers; each language adds its own.
 * @param target - The board and what is connected to it.
 * @param toolchain - What builds the code.
 * @param build - How to build and run it, a line per step.
 * @param notes - Anything else to know first.
 */
export const header = (
  target: FirmwareTarget,
  toolchain: string,
  build: string[],
  notes: string[] = [],
): string[] => [
  `Generated by Echidna for ${target.boardId} (${target.boardName}).`,
  `Toolchain: ${toolchain}`,
  ...(build.length ? ["", "Build and run:", ...build.map((b) => `  ${b}`)] : []),
  "",
  "Wiring, as in the project:",
  ...(target.peripherals.length
    ? target.peripherals.map((p) => `  ${describe(p, target)}`)
    : ["  Nothing is connected to the board's slots or GPIO pins yet."]),
  ...(target.ignoredBoards.length
    ? [
        "",
        `Other dev boards in the project (${target.ignoredBoards.join(", ")}) need code of their own.`,
      ]
    : []),
  "",
  `Prints one line per reading: "${READING_FORMAT}".`,
  ...(notes.length ? ["", ...notes] : []),
];

/** Lines as a block comment for C-family languages. */
export const blockComment = (lines: string[]) => [
  "/*",
  ...lines.map((l) => (l ? ` * ${l}` : " *")),
  " */",
];

/** Lines as `//` comments. */
export const lineComment = (lines: string[]) => lines.map((l) => (l ? `// ${l}` : "//"));

/** Indents every non-empty line by `depth` steps of `unit`. */
export const indent = (lines: string[], depth = 1, unit = "    ") =>
  lines.map((l) => (l ? unit.repeat(depth) + l : l));

/** Joins lines into a file, ending with a newline. */
export const file = (lines: string[]) => `${lines.join("\n")}\n`;

/** The readings each peripheral prints, as `[quantity, unit description]`, for the host-side reader. */
export const readingsOf = (p: Peripheral): [string, string][] => {
  switch (p.type) {
    case "bme280":
      return [
        ["temperature_c", "°C"],
        ["pressure_pa", "Pa"],
        ["humidity_pct", "%"],
      ];
    case "ds18b20":
      return [["temperature_c", "°C"]];
    case "hcsr04":
      return [["distance_m", "m"]];
    case "input":
      return [["level", "0 or 1"]];
    case "output":
    case "i2c":
      return [];
  }
};
